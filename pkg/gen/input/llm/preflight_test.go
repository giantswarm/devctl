// Alignment commits with git add -A, which skips ignored paths, so an ignored
// output would make it commit only part of the change.
func TestPreflight_IgnoredOutputs(t *testing.T) {
	testCases := []struct {
		name    string
		files   map[string]string
		tracked []string
		want    []string
	}{
		{
			name:  "ignored AGENTS.md",
			files: map[string]string{".gitignore": "AGENTS.md\n"},
			want:  []string{"AGENTS.md"},
		},
		{
			name:  "ignored AGENTS.md next to instructions that need migration",
			files: map[string]string{".gitignore": "AGENTS.md\n", "CLAUDE.md": "Run make test.\n"},
			want:  []string{"AGENTS.md", "CLAUDE.md"},
		},
		{
			name:  "ignored Claude directory",
			files: map[string]string{".gitignore": ".claude/\n"},
			want:  []string{".claude/skills"},
		},
		{
			name:  "a directory pattern ignores the shared skills but not the link to them",
			files: map[string]string{".gitignore": "skills/\n"},
			want:  []string{".agents/skills"},
		},
		{
			name:  "ignored skill files",
			files: map[string]string{".gitignore": "SKILL.md\n"},
			want:  []string{".agents/skills"},
		},
		{
			name:  "ignored skills directory and files are one finding",
			files: map[string]string{".gitignore": ".agents/\n"},
			want:  []string{".agents/skills"},
		},
		{
			name:    "a tracked file is committed anyway",
			files:   map[string]string{".gitignore": "AGENTS.md\n", "AGENTS.md": managedBlock},
			tracked: []string{"AGENTS.md"},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			root := newCheckout(t)
			writeFiles(t, root, tc.files)
			if len(tc.tracked) > 0 {
				git(t, root, append([]string{"add", "-f", "--"}, tc.tracked...)...)
			}

			report, err := check(t, root, llm.DefaultMode)
			require.NoError(t, err)
			require.Equal(t, tc.want, findingPaths(t, report))
		})
	}
}

// Only the absence of a checkout skips the check. Any other Git failure
// could hide ignored outputs.
func TestPreflight_GitFailure(t *testing.T) {
	root := newCheckout(t)
	writeFiles(t, root, map[string]string{".git/config": "[broken\n"})

	_, err := check(t, root, llm.DefaultMode)
	require.ErrorContains(t, err, "bad config line 1")
}

func TestPreflight_OutsideGitCheckout(t *testing.T) {
	root := isolatedDir(t)
	writeFiles(t, root, map[string]string{".gitignore": "AGENTS.md\n"})

	report, err := check(t, root, llm.DefaultMode)
	require.NoError(t, err)
	require.Empty(t, report.Findings)
}

// check returns the findings of planning the changes to root in mode.
func check(t *testing.T, root string, mode llm.Mode) (llm.Report, error) {
	t.Helper()
	_, report, err := llm.Plan(t.Context(), root, mode, testBody)
	return report, err
}

// newCheckout returns an empty Git checkout, as alignment runs in one.
func newCheckout(t *testing.T) string {
	t.Helper()
	root := isolatedDir(t)
	git(t, root, "init", "-q")
	return root
}

// isolatedDir returns an empty directory in which Git reads neither the
// developer's configuration and ignore files nor an enclosing repository.
func isolatedDir(t *testing.T) string {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", home)
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	root := t.TempDir()
	t.Setenv("GIT_CEILING_DIRECTORIES", filepath.Dir(root))
	return root
}

func git(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.CommandContext(t.Context(), "git", args...) // #nosec G204 -- tests pass fixed git subcommands
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, string(out))
}

func writeFiles(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, content := range files {
		path := filepath.Join(root, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o750))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}
}

func writeLinks(t *testing.T, root string, links map[string]string) {
	t.Helper()
	for name, target := range links {
		path := filepath.Join(root, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o750))
		require.NoError(t, os.Symlink(target, path))
	}
}

func findingPaths(t *testing.T, report llm.Report) []string {
	t.Helper()
	var paths []string
	for _, f := range report.Findings {
		require.NotEmpty(t, f.Fix, "finding for %s names no fix", f.Path)
		paths = append(paths, f.Path)
	}
	return paths
}
