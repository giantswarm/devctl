const managedBlock = "<!-- BEGIN devctl-managed: generated by devctl -->\n- Use conventional commits.\n<!-- END devctl-managed -->\n"

func TestPreflight_DefaultMode(t *testing.T) {
	testCases := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{
			name: "a repository without instructions is ready",
		},
		{
			name:  "Claude instructions need migration",
			files: map[string]string{"CLAUDE.md": "Run make test.\n"},
			want:  []string{"CLAUDE.md"},
		},
		{
			name:  "a migrated repository is ready",
			files: map[string]string{"AGENTS.md": managedBlock + "\n## This repository\n", "CLAUDE.md": "@AGENTS.md\n"},
		},
		{
			name:  "a block after a byte order mark",
			files: map[string]string{"AGENTS.md": "\ufeff" + managedBlock},
		},
		{
			name:  "an AGENTS.md with only whitespace is new",
			files: map[string]string{"AGENTS.md": "\n  \n"},
		},
		{
			name:  "AGENTS.md without a block needs migration",
			files: map[string]string{"AGENTS.md": "Run make test.\n"},
			want:  []string{"AGENTS.md"},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			root := newCheckout(t)
			writeFiles(t, root, tc.files)

			report, err := check(t, root, llm.DefaultMode)
			require.NoError(t, err)
			require.Equal(t, tc.want, findingPaths(t, report))
		})
	}
}

func TestPreflight_MalformedMarkers(t *testing.T) {
	for _, mode := range []llm.Mode{llm.DefaultMode, llm.MigrationMode} {
		root := newCheckout(t)
		writeFiles(t, root, map[string]string{"AGENTS.md": "Intro.\n<!-- END devctl-managed -->\n"})

		report, err := check(t, root, mode)
		require.NoError(t, err)
		require.Equal(t, []string{"AGENTS.md"}, findingPaths(t, report))
		require.Equal(t, "the end marker on line 2 has no begin marker", report.Findings[0].Problem)
		require.Contains(t, report.Findings[0].Fix, "remove both markers")
	}
}

func TestPreflight_Links(t *testing.T) {
	migrated := map[string]string{"AGENTS.md": managedBlock}
	testCases := []struct {
		name  string
		files map[string]string
		links map[string]string
		want  []string
	}{
		{
			name:  "Claude files may link to AGENTS.md",
			files: migrated,
			links: map[string]string{"CLAUDE.md": "AGENTS.md", ".claude/CLAUDE.md": "../AGENTS.md"},
		},
		{
			name:  "a link to a missing AGENTS.md holds no instructions",
			links: map[string]string{"CLAUDE.md": "AGENTS.md"},
		},
		{
			name:  "a linked AGENTS.md would put the block into another file",
			files: map[string]string{"CONTRIBUTING.md": managedBlock},
			links: map[string]string{"AGENTS.md": "CONTRIBUTING.md", "CLAUDE.md": "AGENTS.md"},
			want:  []string{"AGENTS.md"},
		},
		{
			name:  "a Claude file linking elsewhere",
			files: map[string]string{"AGENTS.md": managedBlock, "docs/claude.md": "Local.\n"},
			links: map[string]string{".claude/CLAUDE.md": "../docs/claude.md"},
			want:  []string{".claude/CLAUDE.md"},
		},
		{
			name:  "linked parent directories",
			files: map[string]string{"AGENTS.md": managedBlock, "shared/claude/settings.json": "{}\n", "shared/agents/skills/a/SKILL.md": "a\n"},
			links: map[string]string{".claude": "shared/claude", ".agents": "shared/agents"},
			want:  []string{".agents", ".claude"},
		},
		{
			name:  "a linked skills directory",
			files: map[string]string{"AGENTS.md": managedBlock, "skills/a/SKILL.md": "a\n"},
			links: map[string]string{".agents/skills": "../skills"},
			want:  []string{".agents/skills"},
		},
	}

	for _, tc := range testCases {
		for _, mode := range []llm.Mode{llm.DefaultMode, llm.MigrationMode} {
			t.Run(tc.name, func(t *testing.T) {
				root := newCheckout(t)
				writeFiles(t, root, tc.files)
				writeLinks(t, root, tc.links)

				report, err := check(t, root, mode)
				require.NoError(t, err)
				require.Equal(t, tc.want, findingPaths(t, report))
			})
		}
	}
}

