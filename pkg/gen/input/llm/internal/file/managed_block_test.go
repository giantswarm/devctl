package file

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

const testBlockBody = "## Giant Swarm conventions\n\n- Use conventional commits.\n"

const testBlock = `<!-- BEGIN devctl-managed: generated by devctl from https://github.com/giantswarm/devctl/blob/main/pkg/gen/input/llm/internal/file/agents_block.md.template, edits in this block are overwritten -->
## Giant Swarm conventions

- Use conventional commits.
<!-- END devctl-managed -->
`

var testBlockCRLF = strings.ReplaceAll(testBlock, "\n", "\r\n")

func Test_MergeManagedBlock(t *testing.T) {
	testCases := []struct {
		name     string
		existing string
		expected string
	}{
		{
			name:     "no file",
			existing: "",
			expected: testBlock + "\n## This repository\n",
		},
		{
			name:     "existing instructions without a block are kept below it",
			existing: "# CLAUDE.md\n\nRun `make test`.  \n\n\n",
			expected: testBlock + "\n# CLAUDE.md\n\nRun `make test`.  \n\n\n",
		},
		{
			name: "an existing block is replaced in place",
			existing: "Read this first.\r\n\r\n" +
				"<!-- BEGIN devctl-managed -->\n- An edit someone made inside the block.\n<!-- END devctl-managed -->\n" +
				"\r\n## This repository\r\n\r\nUse tabs.\r\n",
			expected: "Read this first.\r\n\r\n" +
				testBlockCRLF +
				"\r\n## This repository\r\n\r\nUse tabs.\r\n",
		},
		{
			name:     "another tool's managed block is content",
			existing: "<!-- BEGIN:nextjs-agent-rules -->\nRead the Next.js docs.\n<!-- END:nextjs-agent-rules -->\n",
			expected: testBlock + "\n<!-- BEGIN:nextjs-agent-rules -->\nRead the Next.js docs.\n<!-- END:nextjs-agent-rules -->\n",
		},
		{
			name:     "a marker with a longer name is content",
			existing: "<!-- BEGIN devctl-managed-extras -->\nLocal.\n",
			expected: testBlock + "\n<!-- BEGIN devctl-managed-extras -->\nLocal.\n",
		},
		{
			name:     "a begin marker followed by more text is content",
			existing: "<!-- BEGIN devctl-managed: x --> <!-- keep -->\nLocal.\n",
			expected: testBlock + "\n<!-- BEGIN devctl-managed: x --> <!-- keep -->\nLocal.\n",
		},
		{
			name:     "a file with only whitespace is new",
			existing: "\n  \n",
			expected: testBlock + "\n## This repository\n",
		},
		{
			name:     "an end marker on the last line without a newline",
			existing: "Local.\n<!-- BEGIN devctl-managed -->\n- old\n<!-- END devctl-managed -->",
			expected: "Local.\n" + testBlock,
		},
		{
			name:     "whitespace around markers",
			existing: "  <!-- BEGIN devctl-managed -->  \n- old\n\t<!-- END devctl-managed -->\nLocal.\n",
			expected: testBlock + "Local.\n",
		},
		{
			name:     "markers in a code fence are content",
			existing: "How it works:\n\n```markdown\n<!-- BEGIN devctl-managed -->\n<!-- END devctl-managed -->\n```\n",
			expected: testBlock + "\nHow it works:\n\n```markdown\n<!-- BEGIN devctl-managed -->\n<!-- END devctl-managed -->\n```\n",
		},
		{
			name: "a block next to a fenced example",
			existing: "<!-- BEGIN devctl-managed -->\n- old\n<!-- END devctl-managed -->\n" +
				"\n~~~\n<!-- END devctl-managed -->\n~~~\n",
			expected: testBlock + "\n~~~\n<!-- END devctl-managed -->\n~~~\n",
		},
		{
			name:     "a fence closes only with the same character and at least its length",
			existing: "````\n```\n~~~~\n<!-- END devctl-managed -->\n````\n",
			expected: testBlock + "\n````\n```\n~~~~\n<!-- END devctl-managed -->\n````\n",
		},
		{
			name:     "a CRLF file gets a CRLF block",
			existing: "# Title\r\n",
			expected: testBlockCRLF + "\r\n# Title\r\n",
		},
		{
			name:     "CRLF marker lines",
			existing: "<!-- BEGIN devctl-managed -->\r\n- old\r\n<!-- END devctl-managed -->\r\nLocal.\r\n",
			expected: testBlockCRLF + "Local.\r\n",
		},
		{
			name:     "a byte order mark stays first",
			existing: "\ufeff# Title\n",
			expected: "\ufeff" + testBlock + "\n# Title\n",
		},
		{
			name:     "a begin marker after a byte order mark",
			existing: "\ufeff<!-- BEGIN devctl-managed -->\n- old\n<!-- END devctl-managed -->\nLocal.\n",
			expected: "\ufeff" + testBlock + "Local.\n",
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := MergeManagedBlock([]byte(tc.existing), testBlockBody)
			require.NoError(t, err)
			require.Equal(t, tc.expected, string(got))

			again, err := MergeManagedBlock(got, testBlockBody)
			require.NoError(t, err)
			require.Equal(t, string(got), string(again), "a repeated run must not change the file")
		})
	}
}

func Test_MergeManagedBlock_BodyWithoutTrailingNewline(t *testing.T) {
	got, err := MergeManagedBlock(nil, "- Use conventional commits.")
	require.NoError(t, err)
	require.Equal(t, `<!-- BEGIN devctl-managed: generated by devctl from https://github.com/giantswarm/devctl/blob/main/pkg/gen/input/llm/internal/file/agents_block.md.template, edits in this block are overwritten -->
- Use conventional commits.
<!-- END devctl-managed -->

## This repository
`, string(got))
}

func Test_MergeManagedBlock_InvalidMarkers(t *testing.T) {
	const (
		begin = "<!-- BEGIN devctl-managed -->\n"
		end   = "<!-- END devctl-managed -->\n"
	)
	testCases := []struct {
		name     string
		existing string
		problem  string
	}{
		{name: "begin without end", existing: "Intro.\n" + begin + "- rule\n", problem: "the begin marker on line 2 has no end marker"},
		{name: "end without begin", existing: "Intro.\n- rule\n" + end, problem: "the end marker on line 3 has no begin marker"},
		{name: "end before begin", existing: end + "Local.\n" + begin, problem: "the end marker on line 1 comes before the begin marker on line 3"},
		{name: "nested begin", existing: begin + begin + "- rule\n" + end + end, problem: "found 2 begin markers (lines 1, 2) and 2 end markers (lines 4, 5)"},
		{name: "two blocks", existing: begin + "- one\n" + end + "Local.\n" + begin + "- two\n" + end, problem: "found 2 begin markers (lines 1, 5) and 2 end markers (lines 3, 7)"},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := MergeManagedBlock([]byte(tc.existing), testBlockBody)
			require.True(t, IsInvalidManagedBlock(err), "got %v", err)
			require.ErrorContains(t, err, tc.problem)
			require.ErrorContains(t, err, "remove both markers to have the block added again")
		})
	}
}

