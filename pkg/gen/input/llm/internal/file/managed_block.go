package file

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/giantswarm/microerror"
)

const (
	managedBlockBegin = "<!-- BEGIN devctl-managed: generated by devctl, edits in this block are overwritten -->"
	managedBlockEnd   = "<!-- END devctl-managed -->"

	localSection = "## This repository\n"
)

// mergeManagedBlock returns the content of an AGENTS.md with body as its
// devctl-managed block. Without existing content, the result is the block
// followed by an empty section for the repository's own instructions. Existing
// content without a block keeps every byte, below the new block. An existing
// block is replaced in place, keeping every byte around it. The block uses the
// line ending of the file's first line, and a byte order mark stays first.
func mergeManagedBlock(existing []byte, body string) ([]byte, error) {
	body = strings.ReplaceAll(body, "\r\n", "\n")
	if !strings.HasSuffix(body, "\n") {
		body += "\n"
	}
	if m := findMarkers([]byte(body)); len(m.begins) > 0 || len(m.ends) > 0 || m.unclosedFence {
		return nil, microerror.Maskf(invalidBlockBodyError, "the block content must not contain a devctl-managed marker line or an unclosed code fence")
	}

	content, hasBOM := bytes.CutPrefix(existing, utf8BOM)
	eol := lineEnding(content)
	block := []byte(strings.ReplaceAll(managedBlockBegin+"\n"+body+managedBlockEnd+"\n", "\n", eol))

	merged := make([]byte, 0, len(existing)+len(block)+len(localSection)+2*len(eol))
	if hasBOM {
		merged = append(merged, utf8BOM...)
	}
	if len(bytes.TrimSpace(content)) == 0 {
		merged = append(merged, block...)
		merged = append(merged, eol...)
		return append(merged, strings.ReplaceAll(localSection, "\n", eol)...), nil
	}

	start, end, found, err := findManagedBlock(content)
	if err != nil {
		return nil, microerror.Mask(err)
	}
	if !found {
		merged = append(merged, block...)
		merged = append(merged, eol...)
		return append(merged, content...), nil
	}
	merged = append(merged, content[:start]...)
	merged = append(merged, block...)
	return append(merged, content[end:]...), nil
}

var utf8BOM = []byte("\ufeff")

// lineEnding returns the line ending of content's first line: CRLF or LF.
func lineEnding(content []byte) string {
	if i := bytes.IndexByte(content, '\n'); i > 0 && content[i-1] == '\r' {
		return "\r\n"
	}
	return "\n"
}

type markerLine struct {
	number     int
	start, end int
}

type markers struct {
	begins, ends  []markerLine
	unclosedFence bool
}

// findMarkers finds the marker lines in content. Lines in fenced code blocks
// are skipped, so that instructions can show the markers as an example.
func findMarkers(content []byte) markers {
	var m markers
	var fence []byte
	offset, number := 0, 0
	for line := range bytes.Lines(content) {
		number++
		current := markerLine{number: number, start: offset, end: offset + len(line)}
		offset = current.end

		if fence != nil {
			if closesFence(line, fence) {
				fence = nil
			}
			continue
		}
		if fence = opensFence(line); fence != nil {
			continue
		}
		switch {
		case isManagedBlockBegin(line):
			m.begins = append(m.begins, current)
		case isManagedBlockEnd(line):
			m.ends = append(m.ends, current)
		}
	}
	m.unclosedFence = fence != nil
	return m
}

// opensFence returns the run of backticks or tildes that opens a fenced code
// block on line, or nil.
func opensFence(line []byte) []byte {
	line = bytes.TrimLeft(line, " \t")
	if len(line) == 0 || (line[0] != '`' && line[0] != '~') {
		return nil
	}
	n := 0
	for n < len(line) && line[n] == line[0] {
		n++
	}
	if n < 3 {
		return nil
	}
	return line[:n]
}

// closesFence reports whether line closes the fence opened by fence: the same
// character, at least as often, and nothing else.
func closesFence(line, fence []byte) bool {
	line = bytes.TrimSpace(line)
	return len(line) >= len(fence) && len(bytes.Trim(line, string(fence[:1]))) == 0
}

// findManagedBlock returns the byte span of the managed block in content, from
// the start of its begin marker line to the end of its end marker line,
// including that line's terminator. Content without markers has no block;
// any markers other than one begin followed by one end are an error, because
// replacing a guessed span could overwrite the repository's own instructions.
func findManagedBlock(content []byte) (start, end int, found bool, err error) {
	start, end, found, problem := locateManagedBlock(content)
	if problem != "" {
		return 0, 0, false, microerror.Maskf(invalidManagedBlockError, "%s; %s", problem, ManagedBlockFix)
	}
	return start, end, found, nil
}

// ManagedBlockFix tells how to repair the markers that CheckManagedBlock
// reports a problem with.
const ManagedBlockFix = "keep exactly one begin marker followed by one end marker, or remove both markers to have the block added again"

// CheckManagedBlock reports whether content has a devctl-managed block, or
// what is wrong with its markers.
func CheckManagedBlock(content []byte) (found bool, problem string) {
	content, _ = bytes.CutPrefix(content, utf8BOM)
	_, _, found, problem = locateManagedBlock(content)
	return found, problem
}

func locateManagedBlock(content []byte) (start, end int, found bool, problem string) {
	m := findMarkers(content)
	begins, ends := m.begins, m.ends

	switch {
	case len(begins) == 0 && len(ends) == 0:
		return 0, 0, false, ""
	case len(begins) == 1 && len(ends) == 1 && begins[0].number < ends[0].number:
		return begins[0].start, ends[0].end, true, ""
	case len(begins) == 1 && len(ends) == 1:
		problem = fmt.Sprintf("the end marker on line %d comes before the begin marker on line %d", ends[0].number, begins[0].number)
	case len(begins) == 1 && len(ends) == 0:
		problem = fmt.Sprintf("the begin marker on line %d has no end marker", begins[0].number)
	case len(begins) == 0 && len(ends) == 1:
		problem = fmt.Sprintf("the end marker on line %d has no begin marker", ends[0].number)
	default:
		problem = fmt.Sprintf("found %s and %s", countMarkers("begin", begins), countMarkers("end", ends))
	}
	return 0, 0, false, problem
}

func countMarkers(kind string, lines []markerLine) string {
	switch len(lines) {
	case 0:
		return "no " + kind + " marker"
	case 1:
		return fmt.Sprintf("1 %s marker (line %d)", kind, lines[0].number)
	}
	numbers := make([]string, len(lines))
	for i, l := range lines {
		numbers[i] = fmt.Sprint(l.number)
	}
	return fmt.Sprintf("%d %s markers (lines %s)", len(lines), kind, strings.Join(numbers, ", "))
}

// Earlier wordings of the begin marker are recognized as long as they name the
// block, so that the explanation in the marker can change.
func isManagedBlockBegin(line []byte) bool {
	rest, ok := bytes.CutPrefix(bytes.TrimSpace(line), []byte("<!-- BEGIN devctl-managed"))
	// The comment ends the line: text after it belongs to the repository.
	if !ok || bytes.Index(rest, []byte("-->")) != len(rest)-len("-->") {
		return false
	}
	// The name ends here: devctl-managed-extras would be another block.
	return bytes.Equal(rest, []byte(" -->")) || bytes.HasPrefix(rest, []byte(":"))
}

func isManagedBlockEnd(line []byte) bool {
	return bytes.Equal(bytes.TrimSpace(line), []byte(managedBlockEnd))
}
