package file

import (
	"bytes"
	"strings"

	"github.com/giantswarm/microerror"
)

const (
	managedBlockBegin = "<!-- BEGIN devctl-managed: generated by devctl, edits in this block are overwritten -->"
	managedBlockEnd   = "<!-- END devctl-managed -->"

	localSection = "## This repository\n"
)

// mergeManagedBlock returns the content of an AGENTS.md with body as its
// devctl-managed block. Without existing content, the result is the block
// followed by an empty section for the repository's own instructions. Existing
// content without a block keeps every byte, below the new block. An existing
// block is replaced in place, keeping every byte around it.
func mergeManagedBlock(existing []byte, body string) ([]byte, error) {
	if !strings.HasSuffix(body, "\n") {
		body += "\n"
	}
	block := managedBlockBegin + "\n" + body + managedBlockEnd + "\n"
	if len(existing) == 0 {
		return []byte(block + "\n" + localSection), nil
	}

	start, end, found, err := findManagedBlock(existing)
	if err != nil {
		return nil, microerror.Mask(err)
	}
	if !found {
		return append([]byte(block+"\n"), existing...), nil
	}

	merged := make([]byte, 0, len(existing)+len(block))
	merged = append(merged, existing[:start]...)
	merged = append(merged, block...)
	merged = append(merged, existing[end:]...)
	return merged, nil
}

// findManagedBlock returns the byte span of the managed block in content, from
// the start of its begin marker line to the end of its end marker line,
// including that line's terminator. Content without markers has no block;
// any markers other than one begin followed by one end are an error, because
// replacing a guessed span could overwrite the repository's own instructions.
func findManagedBlock(content []byte) (start, end int, found bool, err error) {
	var begins, ends []int
	for offset, lineNumber := 0, 1; offset < len(content); lineNumber++ {
		line := content[offset:]
		next := len(content)
		if i := bytes.IndexByte(line, '\n'); i >= 0 {
			line = line[:i]
			next = offset + i + 1
		}
		switch {
		case isManagedBlockBegin(line):
			begins = append(begins, lineNumber)
			start = offset
		case isManagedBlockEnd(line):
			ends = append(ends, lineNumber)
			end = next
		}
		offset = next
	}

	switch {
	case len(begins) == 0 && len(ends) == 0:
		return 0, 0, false, nil
	case len(begins) == 1 && len(ends) == 1 && begins[0] < ends[0]:
		return start, end, true, nil
	}
	return 0, 0, false, microerror.Maskf(invalidManagedBlockError,
		"expected one devctl-managed begin marker followed by one end marker, found begin markers on lines %v and end markers on lines %v; "+
			"keep a single pair, or remove all markers to have the block added again", begins, ends)
}

// Earlier wordings of the begin marker are recognized as long as they name the
// block, so that the explanation in the marker can change.
func isManagedBlockBegin(line []byte) bool {
	rest, ok := bytes.CutPrefix(bytes.TrimSpace(line), []byte("<!-- BEGIN devctl-managed"))
	if !ok || !bytes.HasSuffix(rest, []byte("-->")) {
		return false
	}
	// The name ends here: devctl-managed-extras would be another block.
	return bytes.Equal(rest, []byte(" -->")) || bytes.HasPrefix(rest, []byte(":"))
}

func isManagedBlockEnd(line []byte) bool {
	return bytes.Equal(bytes.TrimSpace(line), []byte(managedBlockEnd))
}
