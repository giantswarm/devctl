package renovate

import (
	"bytes"
	"os"
	"path/filepath"

	"github.com/giantswarm/microerror"
)

// generatedHeader starts every configuration `devctl gen renovate` writes,
// renovate.json5 and a fork line's renovate.json alike.
var generatedHeader = []byte("// DO NOT EDIT. This file is generated by `devctl gen renovate")

// ConfigPaths are the configuration files Renovate reads in a repository,
// relative to its root, in Renovate's precedence order for GitHub.
var ConfigPaths = []string{
	"renovate.json", "renovate.jsonc", "renovate.json5",
	".github/renovate.json", ".github/renovate.jsonc", ".github/renovate.json5",
	".renovaterc", ".renovaterc.json", ".renovaterc.jsonc", ".renovaterc.json5",
}

// Generated says whether a Renovate configuration is one `devctl gen
// renovate` wrote.
func Generated(config []byte) bool {
	return bytes.HasPrefix(config, generatedHeader)
}

// OwnConfig says whether the repository checked out at dir carries a
// Renovate configuration of its own at any of [ConfigPaths]: one that
// `devctl gen renovate` did not write. A generated configuration is
// devctl's, regenerated on every align run, so a renovate-custom.json5
// added after it is extended and a template change reaches it.
func OwnConfig(dir string) (bool, error) {
	for _, p := range ConfigPaths {
		path := filepath.Join(dir, p)
		info, err := os.Stat(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return false, microerror.Mask(err)
		}
		if info.IsDir() {
			continue
		}
		content, err := os.ReadFile(path) // #nosec G304 -- fixed Renovate config names below dir
		if err != nil {
			return false, microerror.Mask(err)
		}
		if !Generated(content) {
			return true, nil
		}
	}
	return false, nil
}
