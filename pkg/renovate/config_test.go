// The scaffold and align-files must recognize the newly supported config
// formats as existing configuration rather than generate a competing file.
func TestOwnConfigAdditionalFormats(t *testing.T) {
	paths := []string{"renovate.jsonc", ".github/renovate.jsonc", ".renovaterc.jsonc", ".renovaterc.json5"}
	for i, path := range paths {
		t.Run("case "+strconv.Itoa(i)+": "+path, func(t *testing.T) {
			dir := t.TempDir()
			found, err := OwnConfig(dir)
			require.NoError(t, err)
			require.False(t, found)
			config := filepath.Join(dir, filepath.FromSlash(path))
			require.NoError(t, os.MkdirAll(filepath.Dir(config), 0750))
			require.NoError(t, os.WriteFile(config, []byte("{}"), 0600))
			found, err = OwnConfig(dir)
			require.NoError(t, err)
			require.True(t, found)
		})
	}
}

// A configuration devctl generated is devctl's, whatever template version
// wrote it: align-files regenerates it. One without the header, beside it or
// alone, is the repository's own.
func TestOwnConfigGenerated(t *testing.T) {
	generated := "// DO NOT EDIT. This file is generated by `devctl gen renovate` and kept in sync\n{}\n"
	fork := "// DO NOT EDIT. This file is generated by `devctl gen renovate --flavour fork`.\n{}\n"
	cases := []struct {
		name  string
		files map[string]string
		want  bool
	}{
		{name: "generated renovate.json5", files: map[string]string{"renovate.json5": generated}},
		{name: "generated fork renovate.json", files: map[string]string{"renovate.json": fork}},
		{name: "hand-written renovate.json5", files: map[string]string{"renovate.json5": "{\n  extends: ['config:base'],\n}\n"}, want: true},
		{name: "generated beside a hand-written one", files: map[string]string{"renovate.json5": generated, ".github/renovate.json5": "{}\n"}, want: true},
		{name: "header below the first line", files: map[string]string{"renovate.json5": "// Repo rules.\n" + generated}, want: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			for p, content := range tc.files {
				path := filepath.Join(dir, filepath.FromSlash(p))
				require.NoError(t, os.MkdirAll(filepath.Dir(path), 0750))
				require.NoError(t, os.WriteFile(path, []byte(content), 0600))
			}
			own, err := OwnConfig(dir)
			require.NoError(t, err)
			require.Equal(t, tc.want, own)
		})
	}
}

// Every configuration the generator writes, plain and fork line, carries the
// header OwnConfig recognizes, so a change to the template's first line
// cannot turn devctl's own file into one align-files never regenerates.
func TestGeneratedMatchesGeneratorOutput(t *testing.T) {
	goldens, err := filepath.Glob(filepath.Join("..", "gen", "input", "renovate", "testdata", "*.golden"))
	require.NoError(t, err)
	require.NotEmpty(t, goldens)
	for _, golden := range goldens {
		t.Run(filepath.Base(golden), func(t *testing.T) {
			content, err := os.ReadFile(golden) // #nosec G304 -- the generator's golden files
			require.NoError(t, err)
			require.True(t, Generated(content))
		})
	}
}
