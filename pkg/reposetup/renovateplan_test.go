func TestPlanRenovate(t *testing.T) {
	on, off := true, false
	reviewers := []string{"team:team-rocket"}
	cases := []struct {
		name      string
		fields    Fields
		ownConfig bool
		want      RenovatePlan
	}{
		{name: "generated CI", fields: Fields{Gen: &GenFields{Flavours: []string{"app"}, CI: &CIFields{Generate: &on}}}, ownConfig: true, want: RenovatePlan{Generate: true}},
		{name: "customer flavour", fields: Fields{Gen: &GenFields{Flavours: []string{"customer"}}}, ownConfig: true, want: RenovatePlan{Generate: true}},
		{name: "no generated CI, no configuration of its own", fields: Fields{ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"generic"}, CI: &CIFields{Generate: &off}}}, want: RenovatePlan{Generate: true}},
		{name: "no generated CI, a configuration of its own", fields: Fields{ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"generic"}}}, ownConfig: true, want: RenovatePlan{PatchReviewers: true}},
		{name: "a configuration of its own, no reviewers", fields: Fields{Gen: &GenFields{Flavours: []string{"generic"}}}, ownConfig: true},
		{name: "no gen", fields: Fields{ChoreReviewers: reviewers}, want: RenovatePlan{PatchReviewers: true}},
		{name: "fork line", fields: Fields{ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"fork"}, CI: &CIFields{Generate: &on}}}, want: RenovatePlan{PatchReviewers: true}},
		{name: "renovate: false", fields: Fields{Renovate: &off, ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"customer"}, CI: &CIFields{Generate: &on}}}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			require.Equal(t, tc.want, PlanRenovate(tc.fields, tc.ownConfig))
		})
	}
}

// The scaffold and every later align run leave a repository with the same
// Renovate files: the scaffold runs genCommands' Renovate line into an empty
// checkout, align-files then runs what PlanRenovate decides for the result,
// and nothing changes -- for an entry on generated CI, one without it, the
// customer flavour, and an entry that generates nothing.
func TestRenovateScaffoldAndAlignAgree(t *testing.T) {
	on, off := true, false
	reviewers := []string{"team:team-rocket"}
	cases := []struct {
		name   string
		fields Fields
		want   bool // the scaffold carries renovate.json5
	}{
		{name: "generated CI", want: true,
			fields: Fields{Name: "service", ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"app"}, Language: "go", CI: &CIFields{Generate: &on}}}},
		{name: "no generated CI", want: true,
			fields: Fields{Name: "configs", ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"generic"}, Language: "generic", CI: &CIFields{Generate: &off}}}},
		{name: "customer flavour", want: true,
			fields: Fields{Name: "customer", Gen: &GenFields{Flavours: []string{"customer"}, Language: "generic"}}},
		{name: "generates nothing",
			fields: Fields{Name: "upstream-fork", ChoreReviewers: reviewers, Gen: &GenFields{Flavours: []string{"fork"}, Language: "go"}}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			var scaffold [][]string
			for _, c := range genCommands(tc.fields, genContext{}) {
				if c[2] == genRenovate {
					scaffold = append(scaffold, c)
				}
			}
			require.NoError(t, runGen(context.Background(), dir, nil, scaffold))
			created := renovateFiles(t, dir)
			require.Equal(t, tc.want, len(created) > 0, created)

			ownConfig, err := renovate.OwnConfig(dir)
			require.NoError(t, err)
			plan := PlanRenovate(tc.fields, ownConfig)
			var align [][]string
			switch {
			case plan.Generate:
				align = append(align, []string{"devctl", "gen", genRenovate})
				align[0] = append(align[0], renovateArgs(tc.fields, tc.fields.Gen.CI != nil && *tc.fields.Gen.CI.Generate, func(string, string) bool { return true })...)
			case plan.PatchReviewers && len(created) > 0:
				align = append(align, append([]string{"devctl", "gen", genRenovate, "reviewers"}, reviewerArgs(tc.fields)...))
			}
			require.NoError(t, runGen(context.Background(), dir, nil, align))
			require.Equal(t, created, renovateFiles(t, dir), "the first align run changes nothing")
		})
	}
}

// A repository without generated CI whose renovate.json5 an earlier align
// run generated, before it had a renovate-custom.json5, gets it regenerated
// once the custom file exists: the next align run extends the custom file
// and leaves it as it is.
func TestRenovateAlignExtendsCustomConfigAddedLater(t *testing.T) {
	off := false
	fields := Fields{Name: "homebrew-formula", Gen: &GenFields{Flavours: []string{"generic"}, Language: "generic", CI: &CIFields{Generate: &off}}}
	dir := t.TempDir()
	// The renovate.json5 of a devctl that extended renovate-custom.json5
	// only when it was present at generation time.
	frozen := "// DO NOT EDIT. This file is generated by `devctl gen renovate` and kept in sync\n" +
		"// by the giantswarm/github align-files workflow. Repo-specific Renovate rules\n" +
		"// belong in renovate-custom.json5 (repo root) -- it is added as the last\n" +
		"// `extends` entry when present and never touched by devctl.\n" +
		"{\n  extends: [\n    'github>giantswarm/renovate-presets:default.json5',\n  ],\n}\n"
	custom := "{\n  homebrew: {\n    enabled: false,\n  },\n}\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "renovate.json5"), []byte(frozen), 0600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "renovate-custom.json5"), []byte(custom), 0600))

	ownConfig, err := renovate.OwnConfig(dir)
	require.NoError(t, err)
	require.False(t, ownConfig)
	require.Equal(t, RenovatePlan{Generate: true}, PlanRenovate(fields, ownConfig))

	align := append([]string{"devctl", "gen", genRenovate}, renovateArgs(fields, false, func(string, string) bool { return true })...)
	require.NoError(t, runGen(context.Background(), dir, nil, [][]string{align}))

	got, err := os.ReadFile(filepath.Join(dir, "renovate.json5")) // #nosec G304 -- test temp dir
	require.NoError(t, err)
	require.Contains(t, string(got), "'github>giantswarm/homebrew-formula:renovate-custom.json5'")
	kept, err := os.ReadFile(filepath.Join(dir, "renovate-custom.json5")) // #nosec G304 -- test temp dir
	require.NoError(t, err)
	require.Equal(t, custom, string(kept))
}

// renovateFiles maps every Renovate configuration in dir to its content.
func renovateFiles(t *testing.T, dir string) map[string]string {
	t.Helper()
	files := map[string]string{}
	for _, p := range renovate.ConfigPaths {
		content, err := os.ReadFile(filepath.Clean(filepath.Join(dir, p)))
		if os.IsNotExist(err) {
			continue
		}
		require.NoError(t, err)
		files[p] = string(content)
	}
	return files
}
