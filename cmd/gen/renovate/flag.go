package renovate

import (
	"regexp"

	"github.com/giantswarm/microerror"
	"github.com/spf13/cobra"
)

const (
	flagInterval          = "interval"
	flagLanguage          = "language"
	flagReviewers         = "reviewers"
	flagCircleCIGenerated = "circleci-generated"
	flagRepoName          = "repo-name"
	flagDeprecated        = "deprecated"
	flagExtends           = "extends"
)

// presetFile is a preset file at the root of giantswarm/renovate-presets.
var presetFile = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*\.json5$`)

type flag struct {
	Interval          string
	Language          string
	Reviewers         []string
	CircleCIGenerated bool
	RepoName          string
	Deprecated        bool
	Extends           []string
}

func (f *flag) Init(cmd *cobra.Command) {
	cmd.Flags().StringVarP(&f.Interval, flagInterval, "i", "", "Check for daily, weekly or monthly updates.")
	cmd.Flags().StringVarP(&f.Language, flagLanguage, "l", "", "Language for Renovate to  monitor for new versions , e.g. go, docker.")
	cmd.Flags().StringSliceVarP(&f.Reviewers, flagReviewers, "r", []string{}, "Reviewers to set in the generated config's `reviewers` array, e.g. team:team-rocket. Repeat or comma-separate for multiple.")
	cmd.Flags().BoolVar(&f.CircleCIGenerated, flagCircleCIGenerated, false, "Disable Renovate updates for the giantswarm/architect orb because .circleci/config.yml is generated by `devctl gen circleci` (which bakes in the orb version).")
	cmd.Flags().StringVar(&f.RepoName, flagRepoName, "", "Repository name under the giantswarm organization for the renovate-custom.json5 extends entry, needed only when that file exists. Defaults to <name> in the giantswarm/<name> path of the git origin remote (https or ssh URL, .git stripped); without an origin remote, or with one outside the giantswarm organization, the command fails and asks for this flag. The directory name is never used.")
	cmd.Flags().BoolVar(&f.Deprecated, flagDeprecated, false, "Extend the renovate-presets deprecated.json5 preset, which disables all routine updates and keeps only security/vulnerability remediation. Set for repos marked lifecycle: deprecated.")
	cmd.Flags().StringSliceVar(&f.Extends, flagExtends, []string{}, "Extra presets of giantswarm/renovate-presets to extend, by file name, e.g. flux.json5. Each is extended as github>giantswarm/renovate-presets:<name>, before the deprecated preset and renovate-custom.json5. Repeat or comma-separate for multiple.")
}

func (f *flag) Validate() error {
	if f.Language == "" {
		return microerror.Maskf(invalidFlagError, "--%s cannot be empty", flagLanguage)
	}
	for _, e := range f.Extends {
		if !presetFile.MatchString(e) {
			return microerror.Maskf(invalidFlagError, "--%s %q is not a preset file of giantswarm/renovate-presets, e.g. flux.json5", flagExtends, e)
		}
	}
	return nil
}
